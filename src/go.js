// Вход в Ноа онлайн по голому адресу /app/.
//
// CDN зеркала держит этот адрес в памяти днями и отдавал вчерашнюю страницу
// со вчерашним кодом — вход «слетал». Поэтому по голому адресу лежит только
// эта пересылка: она всегда одинаковая, и держать её в памяти не страшно. Она
// уводит на адрес с одноразовой меткой — его CDN берёт у сервера свежим.
location.replace(`/app/?v=${Date.now().toString(36)}${location.hash}`);
