// Нормализация выделенного текста перед тем, как он станет «термином».
//
// Через эту функцию проходит всё: и то, что рисуется в шапке попапа
// (Instrument Serif italic, 19px, ОДНА строка с ellipsis — SPEC §5), и то, что
// уходит в AI как термин для объяснения. Полный исходный текст при этом не теряется:
// он отправляется отдельно как контекст.
//
// Почему это не тривиально: SPEC §6 требует «короткое определение термина по сути»,
// но пользователь физически может выделить что угодно — слово, фразу, абзац с
// переносами строк, строку кода с отступами.

/** Дальше термином это уже не назвать: длиннее — только контекст. */
const MAX_CHARS = 60;

/** Обрезать по слову, а не по букве, если «хвост» слова достаточно длинный. */
const MIN_WORD_KEEP = MAX_CHARS * 0.5;

// Кавычки, скобки и знаки препинания по краям. Дефис намеренно не трогаем:
// внутри слова он часть термина («e-mail», «бизнес-логика»).
const EDGE_JUNK = /^[\s"'«»„“”‚‘’(\[{<.,;:!?…]+|[\s"'«»„“”‚‘’)\]}>.,;:!?…]+$/gu;

/**
 * @param {string} raw текст выделения как его отдала система
 * @returns {string} то, что попадёт в шапку попапа и в запрос к AI
 */
export function normalizeTerm(raw) {
  // Переносы строк и табуляция схлопываются в пробел: шапка однострочная, а в запрос
  // к модели «альбедо\n\n   —» уходить не должно.
  const collapsed = String(raw ?? "")
    .replace(/\s+/gu, " ")
    .trim();

  const cleaned = collapsed.replace(EDGE_JUNK, "");
  if (cleaned.length <= MAX_CHARS) return cleaned;

  // Обрезаем по границе слова. Многоточие не дописываем: этот же текст уходит в AI
  // как термин, и «…» модель будет считать частью запроса. Что выделение было
  // длиннее, не теряется — полный текст идёт отдельно контекстом (см. popup-view.js),
  // а в шапке за визуальное усечение отвечает CSS text-overflow.
  const cut = cleaned.slice(0, MAX_CHARS);
  const lastSpace = cut.lastIndexOf(" ");
  return (lastSpace > MIN_WORD_KEEP ? cut.slice(0, lastSpace) : cut).trimEnd();
}
