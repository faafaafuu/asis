//! Онлайн-голоса Microsoft Edge.
//!
//! Те самые нейроголоса (`ru-RU-SvetlanaNeural`, `ru-RU-DmitryNeural`), которыми
//! читает вслух браузер Edge. Звучат почти неотличимо от человека и не требуют
//! ни ключа, ни регистрации.
//!
//! Цена — протокол. Официального API у этой ручки нет: это тот же эндпоинт,
//! которым пользуется сам браузер, поверх WebSocket, с подписью `Sec-MS-GEC`,
//! которую Microsoft ввела в 2024 году и может поменять когда угодно. Поэтому
//! способ остаётся вторым, а не основным: он может перестать работать в любой
//! день, и тогда голос обязан просто вернуться к Piper, а не пропасть совсем.
//!
