/// Голоса, которые собираемся поддержать. Список нужен уже сейчас: окно
/// настройки показывает его в выпадающем списке рядом с голосами Piper.
pub const VOICES: &[(&str, &str)] = &[
    ("ru-RU-SvetlanaNeural", "Светлана — женский"),
    ("ru-RU-DmitryNeural", "Дмитрий — мужской"),
    ("ru-RU-DariyaNeural", "Дарья — женский"),
];

pub const DEFAULT_VOICE: &str = "ru-RU-SvetlanaNeural";

pub async fn speak(voice: &str, _text: &str) -> Result<(), String> {
    let _voice = if voice.trim().is_empty() { DEFAULT_VOICE } else { voice };
    Err("онлайн-голоса ещё не подключены — выберите свой голос в настройках".into())
}

pub fn stop() {}
